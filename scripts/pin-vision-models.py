#!/usr/bin/env python3
"""Pins the prompt writer's MLX models: writes Sources/SwapjutsuApp/Model/VisionModelPins.swift with each model's
Hugging Face commit and the size and SHA-256 of every file the app downloads from it.

The models are the `id:`s in VisionModels.swift, pinned at their current `main`. Run it when a model is added or
should move to a newer commit, and commit the result; the app then downloads exactly that commit and refuses any
file that differs. Large files carry their SHA-256 in the Hub's LFS metadata; small ones are downloaded and hashed.
"""
import fnmatch
import hashlib
import json
import re
import sys
import urllib.request
from pathlib import Path

root = Path(__file__).resolve().parent.parent
options = root / "Sources/SwapjutsuApp/Model/VisionModels.swift"
out = root / "Sources/SwapjutsuApp/Model/VisionModelPins.swift"
# MLXVisionBackend.patterns: the weights, the tokenizer and the configs.
patterns = ["*.safetensors", "*.json", "*.jinja", "*.txt", "*.model", "*.tiktoken"]


def get(url):
    with urllib.request.urlopen(url, timeout=60) as response:
        return response.read()


def pin(repo):
    info = json.loads(get(f"https://huggingface.co/api/models/{repo}/revision/main?blobs=true"))
    commit = info["sha"]
    files = []
    for sibling in sorted(info["siblings"], key=lambda s: s["rfilename"]):
        name = sibling["rfilename"]
        if not any(fnmatch.fnmatch(name, p) for p in patterns):
            continue
        if lfs := sibling.get("lfs"):
            size, sha256 = lfs["size"], lfs["sha256"]
        else:
            data = get(f"https://huggingface.co/{repo}/resolve/{commit}/{name}")
            size, sha256 = len(data), hashlib.sha256(data).hexdigest()
        files.append((name, size, sha256))
    print(f"{repo} {commit} {len(files)} files {sum(f[1] for f in files) / 1e9:.1f} GB", file=sys.stderr)
    return commit, files


repos = re.findall(r'id: "([^"]+/[^"]+)"', options.read_text())
lines = [
    "// Generated by scripts/pin-vision-models.py. Do not edit; run the script to pin a new commit.",
    "",
    "extension VisionModelOption {",
    "    /// Each model's Hugging Face commit and the size and SHA-256 of every file the app downloads from it.",
    "    static let pins: [String: Pin] = [",
]
for repo in repos:
    commit, files = pin(repo)
    lines.append(f'        "{repo}": Pin(')
    lines.append(f'            revision: "{commit}",')
    lines.append("            files: [")
    for name, size, sha256 in files:
        lines.append(f'                .init(path: "{name}", size: {size}, sha256: "{sha256}"),')
    lines.append("            ]),")
lines += ["    ]", "}", ""]
out.write_text("\n".join(lines))
print(out.relative_to(root))
